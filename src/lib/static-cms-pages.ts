const placeholderPatterns = [
  /<p>\s*Плейсхолдер\./i,
  /Документ в разработке/i,
  /этапе 8 запуска сайта/i,
  /compliance-officer/i,
];

export function getStaticCmsPage(slug: string): StaticCmsPage | null {
  return staticPages.get(slug) ?? null;
}

export function isPlaceholderCmsContent(content: string | null | undefined): boolean {
  if (!content) return false;
  return placeholderPatterns.some((pattern) => pattern.test(content));
}

export function hasPublicLicenseDetails(value: string | null | undefined): boolean {
  if (!value) return false;
  const trimmed = value.trim();
  return (
    trimmed !== "" &&
    !trimmed.includes("[") &&
    !/укажет|заказчик/i.test(trimmed) &&
    !/добавляется администратором/i.test(trimmed)
  );
}

export function getPublicLicenseSummaryFromSettings(
  license?: PublicLicenseSettings | null,
): string {
  const number = license?.tomi_number?.trim();
  const date = license?.tomi_date?.trim();

  if (hasPublicLicenseDetails(number)) {
    return date
      ? `Лицензия Росздравнадзора № ${number} от ${date}`
      : `Лицензия Росздравнадзора № ${number}`;
  }

  return getPublicLicenseSummary(undefined);
}

export function getPublicLicenseSummary(value: string | null | undefined): string {
  if (hasPublicLicenseDetails(value)) {
    return value!.trim();
  }

  return "Лицензия Росздравнадзора на техническое обслуживание медицинских изделий. Подлинность подтверждается через реестр Росздравнадзора по ИНН организации.";
}

