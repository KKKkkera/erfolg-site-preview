async function main() {
  // Бренды и категории должны существовать — молча создавать их здесь нельзя,
  // иначе в каталоге появятся дубли с теми, что завёл основной сид.
  const brandIdBySlug = new Map<string, string>();
  const categoryIdBySlug = new Map<string, string>();

  for (const p of PRODUCTS) {
    if (!brandIdBySlug.has(p.brandSlug)) {
      const brand = await db.brand.findUnique({ where: { slug: p.brandSlug } });
      if (!brand) {
        throw new Error(
          `Бренд "${p.brandSlug}" не найден. Сначала: npm run db:seed:brands`,
        );
      }
      brandIdBySlug.set(p.brandSlug, brand.id);
    }
    if (!categoryIdBySlug.has(p.categorySlug)) {
      const category = await db.category.findUnique({
        where: { slug: p.categorySlug },
      });
      if (!category) {
        throw new Error(
          `Категория "${p.categorySlug}" не найдена. Сначала: npm run db:seed`,
        );
      }
      categoryIdBySlug.set(p.categorySlug, category.id);
    }
  }

  let published = 0;
  let drafted = 0;
  // Оборудование ставим после уже существующих Б/У-позиций.
  let sortCounter = 100;

  for (const p of PRODUCTS) {
    sortCounter += 10;
    const reg = REG_NUMBERS[p.slug];
    const hasReg = Boolean(reg?.number?.trim()) && !reg!.number.includes("X");
    const status = hasReg || PUBLISH_WITHOUT_REG ? "ACTIVE" : "DRAFT";
    if (status === "ACTIVE") published += 1;
    else drafted += 1;

    const fields = {
      name: p.name,
      sku: p.sku,
      model: p.model,
      brandId: brandIdBySlug.get(p.brandSlug)!,
      categoryId: categoryIdBySlug.get(p.categorySlug)!,
      shortDesc: p.shortDesc,
      fullDesc: p.fullDesc,
      kind: "EQUIPMENT" as const,
      status: status as "ACTIVE" | "DRAFT",
      priceOnRequest: true,
      isUsed: false,
      // Заглушку вместо номера не пишем: она отрендерилась бы как заявление
      // о наличии РУ (см. src/lib/reg-number.ts).
      regNumber: hasReg ? reg!.number.trim() : null,
      regDate: reg?.date ? new Date(reg.date) : null,
      // Суффикс «| Erfolg» добавляет шаблон title в root layout.
      seoTitle: `${p.name} — поставка по России`,
      seoDesc: p.shortDesc.slice(0, 160),
      sort: sortCounter,
    };

    const product = await db.product.upsert({
      where: { slug: p.slug },
      update: fields,
      create: { slug: p.slug, ...fields },
    });

    await db.productSpec.deleteMany({ where: { productId: product.id } });
    await db.productSpec.createMany({
      data: p.specs.map((s, i) => ({
        productId: product.id,
        key: s.key,
        value: s.value,
        sort: i,
      })),
    });

    await db.productImage.deleteMany({ where: { productId: product.id } });
    await db.productImage.create({
      data: {
        productId: product.id,
        url: imageUrlFor(p.slug),
        alt: imageAltFor(p.name),
        sort: 0,
      },
    });

    console.log(`${status === "ACTIVE" ? "✓ опубликован" : "· черновик   "}  ${p.name}`);
  }

  // Заглушка «На уточнении» у ранее засеянных Б/У-позиций: с ней карточка
  // рендерила «Регистрационное удостоверение № На уточнении». Приводим к NULL —
  // тогда блок РУ просто не показывается (см. src/lib/reg-number.ts).
  const cleaned = await db.product.updateMany({
    where: { regNumber: { in: ["На уточнении", "на уточнении", "-", "—"] } },
    data: { regNumber: null },
  });

  console.log(
    `\nГотово: ${PRODUCTS.length} позиций (опубликовано ${published}, черновиков ${drafted}).`,
  );
  if (cleaned.count > 0) {
    console.log(`Очищено заглушек в номере РУ у прежних товаров: ${cleaned.count}.`);
  }
  if (drafted > 0) {
    console.log(
      "Черновики не видны в каталоге. Впишите номера РУ в REG_NUMBERS вверху файла\n" +
        "и запустите скрипт ещё раз — либо проставьте номер в админке и включите товар.",
    );
  }
  if (PUBLISH_WITHOUT_REG) {
    console.log(
      "\n⚠ ДЕМО-РЕЖИМ: позиции опубликованы без номеров РУ (PUBLISH_WITHOUT_REG = true).\n" +
        "  Перед реальным запуском заполните REG_NUMBERS и выставьте флаг в false.",
    );
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
